"""A variational autoencoder (VAE), the classic generative model for images.

An autoencoder squeezes an image through a small code and rebuilds it. A
VAE (Kingma and Welling, 2013) makes the code a *distribution*, so that new
images can be generated by decoding random codes:

- the encoder maps an image x to a mean mu and a log-variance log_var for
  each of the L code dimensions
- a code is sampled as z = mu + exp(log_var / 2) * eps, eps ~ normal(0, 1).
  Writing the sample this way (the "reparameterization trick") keeps z a
  differentiable function of mu and log_var, so gradients reach the encoder
- the decoder maps z back to pixel scores (logits)

The loss per image (the negative "evidence lower bound", ELBO) is

    reconstruction: binary cross entropy of the decoded pixels, summed
  + KL divergence of normal(mu, sigma^2) from normal(0, 1):
        -1/2 * sum(1 + log_var - mu^2 - exp(log_var))

The KL term pulls every code distribution toward the standard normal, so
decoding samples from normal(0, 1) gives plausible images.
"""

from __future__ import annotations

from losses import binary_cross_entropy_with_logits
from tensor import Tensor
from tensor_nn import TensorLinear, TensorModule


class VAE(TensorModule):
    def __init__(self, *, pixels: int = 784, hidden: int = 256, latent: int = 16, seed: int = 0) -> None:
        self.pixels = pixels
        self.latent = latent
        self.encoder = TensorLinear(pixels, hidden, seed=seed)
        self.to_mean = TensorLinear(hidden, latent, seed=seed + 1)
        self.to_log_var = TensorLinear(hidden, latent, seed=seed + 2)
        self.decoder_hidden = TensorLinear(latent, hidden, seed=seed + 3)
        self.decoder_out = TensorLinear(hidden, pixels, seed=seed + 4)

    def encode(self, images: Tensor) -> tuple[Tensor, Tensor]:
        hidden = self.encoder(images).relu()
        return self.to_mean(hidden), self.to_log_var(hidden)

    def decode(self, codes: Tensor) -> Tensor:
        """Pixel logits; sigmoid of them is the pixel intensity."""

        return self.decoder_out(self.decoder_hidden(codes).relu())

    def __call__(self, images: Tensor, noise: Tensor) -> tuple[Tensor, Tensor, Tensor]:
        """(pixel logits, mu, log_var) for images (B, pixels) and noise eps (B, latent)."""

        mean, log_var = self.encode(images)
        codes = mean + (log_var * 0.5).exp() * noise          # reparameterization trick
        return self.decode(codes), mean, log_var

    def parameters(self) -> list[Tensor]:
        layers = (self.encoder, self.to_mean, self.to_log_var, self.decoder_hidden, self.decoder_out)
        return [parameter for layer in layers for parameter in layer.parameters()]


def vae_loss(logits: Tensor, images: Tensor, mean: Tensor, log_var: Tensor) -> tuple[Tensor, float, float]:
    """(loss, reconstruction, KL), each averaged over the images in the batch."""

    batch = images.shape[0]
    reconstruction = binary_cross_entropy_with_logits(logits, images, reduction="sum") * (1.0 / batch)
    kl = ((1.0 + log_var - mean * mean - log_var.exp()).sum() * (-0.5 / batch))
    return reconstruction + kl, reconstruction.item(), kl.item()
